"""Turn the owner's sky painting into the table the walking world map draws.

    python scripts/make_world_sky.py res/worldmap/sky.webp src/iog_world_sky.inc

The painting is the owner's own artwork (res/worldmap/sky.webp). The map shows
only a low band of sky above its horizon, so the picture is stored wide and
squashed: 768 columns, which the renderer mirrors into a seamless 1536-column
circle, and 84 rows with the horizon glow at the bottom.
"""
import sys
from pathlib import Path
from PIL import Image

WIDTH, HEIGHT, COLOURS = 768, 84, 128


def main(source, output):
    picture = Image.open(source).convert("RGB").resize((WIDTH, HEIGHT), Image.LANCZOS)
    indexed = picture.quantize(COLOURS, method=Image.MEDIANCUT, dither=Image.FLOYDSTEINBERG)
    palette = indexed.getpalette()[:COLOURS * 3]
    pixels = indexed.tobytes()
    lines = ["/* Generated by scripts/make_world_sky.py from res/worldmap/sky.webp. */",
             f"enum {{ kWorldSkyWidth = {WIDTH}, kWorldSkyHeight = {HEIGHT} }};",
             f"static const uint32_t kWorldSkyPalette[{COLOURS}] = {{"]
    for start in range(0, COLOURS, 8):
        lines.append("    " + ", ".join("0x%02x%02x%02x" % tuple(palette[i * 3:i * 3 + 3])
                                        for i in range(start, start + 8)) + ",")
    lines += ["};", "static const uint8_t kWorldSky[kWorldSkyWidth * kWorldSkyHeight] ="]
    for start in range(0, len(pixels), 64):
        lines.append('    "' + "".join("\\%03o" % value for value in pixels[start:start + 64]) + '"')
    lines[-1] += ";"
    Path(output).write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")


if __name__ == "__main__":
    main(*sys.argv[1:3])
